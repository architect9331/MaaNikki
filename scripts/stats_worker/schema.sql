CREATE TABLE IF NOT EXISTS batches (
  id TEXT PRIMARY KEY, day TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS rolls (
  catalog TEXT NOT NULL, name TEXT NOT NULL, slot TEXT NOT NULL, color TEXT NOT NULL,
  count INTEGER NOT NULL, PRIMARY KEY (catalog, name, slot, color)
);
CREATE TABLE IF NOT EXISTS bling_runs (
  id INTEGER PRIMARY KEY AUTOINCREMENT, day TEXT NOT NULL, app TEXT NOT NULL,
  energy INTEGER NOT NULL, gain INTEGER NOT NULL
);
